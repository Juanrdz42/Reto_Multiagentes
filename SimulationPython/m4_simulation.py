class AGVAgent(ap.Agent):
    def setup(self):
        self.agv_id = f"AGV-{self.id}"
        self.pos = np.array([0.0, 0.0], dtype=float)
        self.state = AGV_IDLE
        self.battery = 100.0
        self.speed = 5.0
        self.current_mission = None
        self.distance_traveled = 0.0
        self.completed_missions_count = 0
        self.stuck_steps = 0
        self.path = []
        self.charger = None

        # --- M4: metricas por AGV ---
        self.active_steps = 0     # pasos moviendose hacia un pallet o transportando
        self.charging_steps = 0   # pasos en estacion de carga
        self.idle_steps = 0       # pasos sin mision ni carga
        self.charging_events = 0  # veces que fue a recargar

    def evaluate_mission(self, mission):
        # Si está ocupado o con batería baja, no participa en subastas
        if self.state != AGV_IDLE or self.battery <= LOW_BATTERY_THRESHOLD:
            return None
        strategy = getattr(self.model.p, "strategy", STRATEGY_BASELINE)
        if strategy == STRATEGY_PROPOSED:
            return self._utility_proposed(mission)
        return self._utility_baseline(mission)

    def _distance_to(self, point):
        return np.abs(self.pos[0] - point[0]) + np.abs(self.pos[1] - point[1])

    def _utility_baseline(self, mission):
        # BASELINE: AGV mas cercano al pallet gana, con ligero desempate por bateria
        dist_to_pallet = self._distance_to(mission.origin)
        return - dist_to_pallet + (self.battery * 0.1)

    def _route_congestion(self, mission):
        # Cuenta AGVs activos (no IDLE) cerca del punto medio entre ESTE AGV y
        # el origen de la mision, como proxy de que SU camino hacia alla ya
        # esta ocupado. Debe depender de self.pos: si dependiera solo de la
        # posicion de la mision, todos los AGVs que pujan por la misma mision
        # verian el mismo valor y el termino nunca podria cambiar quien gana.
        midpoint = (self.pos + mission.origin) / 2.0
        return sum(
            1 for other in self.model.agvs
            if other.agv_id != self.agv_id and other.state != AGV_IDLE
            and np.linalg.norm(other.pos - midpoint) < CONGESTION_RADIUS
        )

    def _utility_proposed(self, mission):
        # PROPUESTA: U_{i,m} = -w_d*D_{i,m} + w_b*B_i - w_l*L_i - w_c*C_i
        dist_to_pallet = self._distance_to(mission.origin)
        workload = self.completed_missions_count
        congestion = self._route_congestion(mission)
        return (- W_DISTANCE * dist_to_pallet
                + W_BATTERY * self.battery
                - W_WORKLOAD * workload
                - W_CONGESTION * congestion)

    def determine_if_winner(self, bids):
        """Con el tablon de pujas ya publicado por el Mission Manager (todas
        las pujas son visibles para todos), cada AGV decide POR SI MISMO si
        fue quien ofrecio la mejor puja. En caso de empate, gana el agv_id
        menor (regla determinista que cualquier AGV puede evaluar de forma
        independiente, sin que el Mission Manager compare a nadie)."""
        if self.agv_id not in bids:
            return False
        best_bid = max(bids.values())
        tied = sorted(agv_id for agv_id, b in bids.items() if b == best_bid)
        return self.agv_id == tied[0]

    def accept_mission(self, mission):
        # El AGV acepta la mision para si mismo (auto-asignacion)
        self.current_mission = mission
        self.state = AGV_MOVING_TO_PALLET
        self.path = find_path_grid(self.pos, mission.origin, NAV_GRID)

    def go_to_recharge(self, chargers):
      free = [c for c in chargers if c["occupied_by"] is None]
      if not free:
          return False  # ningún cargador libre: el AGV se queda esperando
      closest = min(free, key=lambda c: np.linalg.norm(self.pos - np.array(c["pos"])))
      closest["occupied_by"] = self.agv_id
      self.charger = closest
      self.state = AGV_CHARGING
      self.charging_events += 1
      self.path = find_path_grid(self.pos, np.array(closest["pos"], dtype=float), NAV_GRID)
      return True

    def peek_next_position(self):
        if not self.path:
            return self.pos.copy()
        target = self.path[0]
        dir_vec = target - self.pos
        dist = np.linalg.norm(dir_vec)
        if dist <= self.speed or dist < 1e-3:
            return target.copy()
        return self.pos + (dir_vec / dist) * self.speed

    def follow_path(self):
        if not self.path:
            return

        target = self.path[0]
        dir_vec = target - self.pos
        dist = np.linalg.norm(dir_vec)

        if dist <= self.speed or dist < 1e-3:
            self.pos = target.copy()
            self.path.pop(0)
            step_dist = dist
        else:
            step_vector = (dir_vec / dist) * self.speed
            self.pos += step_vector
            step_dist = self.speed

        self.distance_traveled += step_dist
        self.battery = max(0.0, self.battery - (step_dist * 0.035))

