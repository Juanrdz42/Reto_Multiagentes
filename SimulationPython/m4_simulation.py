def _to_serializable(obj):
    if isinstance(obj, np.ndarray):
        return [float(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _to_serializable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_to_serializable(v) for v in obj]
    if isinstance(obj, (np.floating, np.integer)):
        return obj.item()
    if obj is None:
        # JsonUtility de Unity no soporta null en campos string: se usa "" en su lugar
        return ""
    return obj

def export_simulation(model, path="simulation_export.json"):
    """Vuelca la geometria estatica y el historial completo de la simulacion
    a un JSON para que Unity lo lea y reproduzca la animacion en 3D.

    Mapeo de coordenadas sugerido en Unity: world_x = sim.x * scale,
    world_z = sim.y * scale, world_y = altura fija (piso). Es decir, el
    plano (x, y) de esta simulacion 2D se convierte en el plano (x, z)
    de Unity (suelo), no en (x, y).
    """
    data = {
        "meta": {
            "width": WIDTH,
            "height": HEIGHT,
            "cell_size": CELL_SIZE,
            "agv_diameter": AGV_DIAMETER,
            "pallet_diameter": PALLET_DIAMETER,
            "pedestrian_radius": PEDESTRIAN_RADIUS,
            "agv_clearance": AGV_CLEARANCE,
            "navigation_obstacles": [z["name"] for z in zones_custom],
            "frame_sample": FRAME_SAMPLE,
            "n_agvs": model.p.n_agvs,
            "total_steps": model.p.steps,
            "total_completed": model.total_completed,
            "total_missions": model.mission_counter - 1,
        },
        "zones": _to_serializable(zones_custom),
        "chargers": [{"name": c["name"], "pos": _to_serializable(c["pos"])} for c in chargers_custom],
        "stations": [{"name": s["name"], "kind": s["kind"], "pos": _to_serializable(s["pos"])}
                     for s in STATION_DEFINITIONS],
        "frames": _to_serializable(model.history),
        "log": model.mission_manager.log,
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Exportado a {path} ({len(model.history)} frames)")



def run_simulation(strategy, n_agvs=4, steps=800, seed=42, flow_scale=1.0):
    """Corre una simulación completa con la estrategia dada, controlando la
    semilla para que baseline y propuesta reciban las mismas condiciones
    (mismo layout, mismos AGVs, mismas misiones generadas por los flujos).
    `flow_scale=1.0` reproduce los intervalos de referencia del reto sin
    modificarlos; valores distintos solo se usan en el escenario experimental
    adicional de la sección "Escenario de mayor contención", mas abajo."""
    random.seed(seed)
    np.random.seed(seed)
    params = {'n_agvs': n_agvs, 'steps': steps, 'strategy': strategy, 'flow_scale': flow_scale}
    model = DistributionCenter(params)
    model.run(display=False)  # evita imprimir el progreso paso a paso en el notebook
    return model


