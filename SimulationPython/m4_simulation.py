class MissionManager:
    """Tablon de anuncios de misiones: SOLO publica misiones y reune las pujas
    que cada AGV calcula por su cuenta. No compara AGVs ni decide quien gana
    (esa decision la toma cada AGVAgent con `determine_if_winner`, ver mas abajo),
    para no convertirse en un controlador centralizado."""

    def __init__(self, missions):
        self.missions = {m.id: m for m in missions}
        self.log = []
        self._published = set()

    def publish_mission(self, mission):
        if mission.id not in self._published:
            self.log.append(f"\n[SUBASTA] Misión {mission.id} publicada (Pallet: {mission.pallet_id})")
            self._published.add(mission.id)

    def collect_bids(self, mission, agv_list):
        bids = {}
        for agv in agv_list:
            bid = agv.evaluate_mission(mission)
            if bid is not None:
                self.log.append(f"  > {agv.agv_id} puja: {bid:.2f}")
                bids[agv.agv_id] = bid
            else:
                self.log.append(f"  > {agv.agv_id} no disponible (Estado: {agv.state}, Bat: {agv.battery:.1f}%)")
        return bids

