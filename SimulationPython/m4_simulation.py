class DistributionCenter(ap.Model):
    def setup(self):
        self.agvs = ap.AgentList(self, self.p.n_agvs, AGVAgent)
        pos_ini = [(80, 50), (80, 120), (80, 180), (80, 240)]
        for i, agv in enumerate(self.agvs):
            agv.pos = np.array(pos_ini[i % len(pos_ini)], dtype=float)

        self.production_line = ProductionLine([
            edge_point(z, "east") for z in zones_custom if z["name"].startswith("Prod Line")
        ])

        self.chargers = [dict(c, occupied_by=None) for c in chargers_custom]

        self.stations = ap.AgentList(self, len(STATION_DEFINITIONS), StationAgent)
        for station, definition in zip(self.stations, STATION_DEFINITIONS):
            station.station_id = definition["name"]
            station.kind = definition["kind"]
            station.pos = np.array(definition["pos"], dtype=float)
        self.stations_by_name = {s.station_id: s for s in self.stations}

        self.mission_manager = MissionManager([])
        self.pallets = {}
        self.mission_counter = 1
        self.pallet_counter = 1
        self.total_completed = 0
        self.reassignments = 0
        self.history = []

        # Ultimo paso en que cada flujo genero mision
        self.last_flow1_t = -FLOW_1_INTERVAL
        self.last_flow2_t = -FLOW_2_INTERVAL
        self.last_flow3_t = -FLOW_3_INTERVAL
        self.last_departure_t = -DOCK_DEPARTURE_INTERVAL

        # --- M4: eventos dinamicos ---
        self.pedestrians = []  # [{"pos": np.array, "until": t}]
        self.last_pedestrian_t = -PEDESTRIAN_INTERVAL
        self.station_alarms = {}  # {station_id: t_restauracion}
        self.last_alarm_t = -STATION_ALARM_INTERVAL

        self._record_frame()

    def spawn_pedestrian(self):
        gx, gy = np.random.randint(0, GRID_W), np.random.randint(0, GRID_H)
        tries = 0
        while NAV_GRID[gy, gx] == 1 and tries < 10:
            gx, gy = np.random.randint(0, GRID_W), np.random.randint(0, GRID_H)
            tries += 1
        if NAV_GRID[gy, gx] == 1:
            return
        pos = grid_to_world((gx, gy))
        if any(np.linalg.norm(pos - agv.pos) < PEDESTRIAN_RADIUS + CELL_SIZE for agv in self.agvs):
            return
        self.pedestrians.append({"pos": pos, "until": self.t + PEDESTRIAN_DURATION})
        self.mission_manager.log.append(f"[EVENTO] Peatón cruza cerca de ({pos[0]:.0f}, {pos[1]:.0f})")

    def update_pedestrians(self):
        if self.t - self.last_pedestrian_t >= PEDESTRIAN_INTERVAL:
            self.spawn_pedestrian()
            self.last_pedestrian_t = self.t
        self.pedestrians = [p for p in self.pedestrians if p["until"] > self.t]

    def update_station_alarms(self):
        for station_id, restore_t in list(self.station_alarms.items()):
            if self.t >= restore_t:
                self.stations_by_name[station_id].restore_service()
                self.mission_manager.log.append(f"[EVENTO] {station_id} vuelve a estar disponible")
                del self.station_alarms[station_id]

        if self.t - self.last_alarm_t >= STATION_ALARM_INTERVAL:
            candidates = [s for s in self.stations if s.is_available()]
            if candidates:
                station = candidates[np.random.randint(len(candidates))]
                station.set_out_of_service()
                self.station_alarms[station.station_id] = self.t + STATION_ALARM_DURATION
                self.mission_manager.log.append(f"[EVENTO] {station.station_id} entra en alarma / fuera de servicio")
            self.last_alarm_t = self.t


    def try_flow_1(self):
        # Flujo 1: Linea de produccion -> Rack o Caja de salida (60%/40%)
        free = self.production_line.free_outlets()
        if not free:
            return False  # sin salidas libres: no se genera, no se acumula

        outlet = free[np.random.randint(len(free))]

        dest_kind = "RACK" if np.random.random() < P_DEST_RACK else "DOCK"
        candidates = [s for s in self.stations if s.kind == dest_kind and s.is_available()]
        if not candidates:
            return False  # sin destino disponible: no se genera
        dest_station = candidates[np.random.randint(len(candidates))]

        pallet_id = f"P{self.pallet_counter}"
        self.pallet_counter += 1
        production_zone = next(z["name"] for z in zones_custom
                               if z["name"].startswith("Prod Line")
                               and np.allclose(edge_point(z, "east"), outlet["pos"]))
        self.pallets[pallet_id] = Pallet(pallet_id, outlet["pos"], production_zone)
        self.production_line.occupy_outlet(outlet, pallet_id)
        dest_station.reserve(pallet_id)

        m_id = f"M{self.mission_counter}"
        self.mission_counter += 1
        mission = Mission(m_id, pallet_id, outlet["pos"], dest_station.pos,
                           origin_station_id=None, dest_station_id=dest_station.station_id,
                           created_at=self.t)
        self.mission_manager.missions[m_id] = mission
        self.mission_manager.log.append(
            f"[FLUJO 1] {m_id}: Producción -> {dest_station.station_id} ({dest_kind}), pallet {pallet_id}"
        )
        return True

    def try_flow_2(self):
        # Flujo 2: Rack -> Caja de camión de salida
        origin_candidates = [s for s in self.stations if s.kind == "RACK" and s.state == STATION_OCCUPIED
                             and not any(m.pallet_id == s.current_pallet_id and m.status != MISSION_COMPLETED
                                         for m in self.mission_manager.missions.values())]
        if not origin_candidates:
            return False
        origin_station = origin_candidates[np.random.randint(len(origin_candidates))]

        dest_candidates = [s for s in self.stations if s.kind == "DOCK" and s.is_available()]
        if not dest_candidates:
            return False
        dest_station = dest_candidates[np.random.randint(len(dest_candidates))]

        pallet_id = origin_station.current_pallet_id
        dest_station.reserve(pallet_id)

        m_id = f"M{self.mission_counter}"
        self.mission_counter += 1
        mission = Mission(m_id, pallet_id, origin_station.pos, dest_station.pos,
                           origin_station_id=origin_station.station_id, dest_station_id=dest_station.station_id,
                           created_at=self.t)
        self.mission_manager.missions[m_id] = mission
        self.mission_manager.log.append(
            f"[FLUJO 2] {m_id}: {origin_station.station_id} -> {dest_station.station_id}, pallet {pallet_id}"
        )
        return True

    def try_flow_3(self):
        # Flujo 3: Caja de camión de entrada -> Rack
        origin_candidates = [s for s in self.stations if s.kind == "DOCK" and s.is_available()]
        if not origin_candidates:
            return False
        origin_station = origin_candidates[np.random.randint(len(origin_candidates))]

        dest_candidates = [s for s in self.stations if s.kind == "RACK" and s.is_available()]
        if not dest_candidates:
            return False
        dest_station = dest_candidates[np.random.randint(len(dest_candidates))]

        pallet_id = f"P{self.pallet_counter}"
        self.pallet_counter += 1
        self.pallets[pallet_id] = Pallet(pallet_id, origin_station.pos, origin_station.station_id)
        origin_station.occupy(pallet_id)
        dest_station.reserve(pallet_id)

        m_id = f"M{self.mission_counter}"
        self.mission_counter += 1
        mission = Mission(m_id, pallet_id, origin_station.pos, dest_station.pos,
                           origin_station_id=origin_station.station_id, dest_station_id=dest_station.station_id,
                           created_at=self.t)
        self.mission_manager.missions[m_id] = mission
        self.mission_manager.log.append(
            f"[FLUJO 3] {m_id}: {origin_station.station_id} -> {dest_station.station_id}, pallet {pallet_id}"
        )
        return True

    def try_dock_departure(self):
        # Intentar vaciar uno de los docks
        occupied_docks = [s for s in self.stations if s.kind == "DOCK" and s.state == STATION_OCCUPIED
                          and self.pallets[s.current_pallet_id].state == P_DELIVERED
                          and not any(m.pallet_id == s.current_pallet_id and m.status != MISSION_COMPLETED
                                      for m in self.mission_manager.missions.values())]
        if not occupied_docks:
            return False
        dock = occupied_docks[np.random.randint(len(occupied_docks))]
        self.mission_manager.log.append(
            f"[DESPACHO] Camión recoge {dock.current_pallet_id} en {dock.station_id}, dock queda libre"
        )
        self.pallets[dock.current_pallet_id].removed = True
        self.pallets[dock.current_pallet_id].storage_zone = None
        dock.release()
        return True

    def run_flow_generator(self):
        # Correr la revision y generacion de cada flujo. `flow_scale` es un
        # parametro opcional (default 1.0 = intervalos de referencia del reto
        # sin modificar) que permite correr un escenario experimental adicional
        # con mas o menos misiones por unidad de tiempo, sin tocar el escenario
        # de referencia por default.
        scale = getattr(self.p, "flow_scale", 1.0)
        f1, f2, f3 = FLOW_1_INTERVAL / scale, FLOW_2_INTERVAL / scale, FLOW_3_INTERVAL / scale
        if self.t - self.last_flow1_t >= f1:
            if self.try_flow_1():
                self.last_flow1_t = self.t
        if self.t - self.last_flow2_t >= f2:
            if self.try_flow_2():
                self.last_flow2_t = self.t
        if self.t - self.last_flow3_t >= f3:
            if self.try_flow_3():
                self.last_flow3_t = self.t
        if self.t - self.last_departure_t >= DOCK_DEPARTURE_INTERVAL:
            if self.try_dock_departure():
                self.last_departure_t = self.t

    def _record_frame(self):
        if self.t % FRAME_SAMPLE != 0:
            return
        self.history.append({
            "t": self.t,
            "agvs": [{"id": a.agv_id, "pos": a.pos.copy(), "battery": a.battery, "state": a.state} for a in self.agvs],
            "pallets": [{"id": p.id, "pos": p.pos.copy(), "state": p.state, "storage_zone": p.storage_zone, "storage_level": p.storage_level, "removed": p.removed} for p in self.pallets.values()],
            "stations": [{"id": s.station_id, "state": s.state, "pallet": s.current_pallet_id} for s in self.stations],
            "missions": [{"id": m.id, "pallet": m.pallet_id, "status": m.status, "assigned": m.assigned_to}
                        for m in self.mission_manager.missions.values()
                        if m.status != MISSION_COMPLETED
                        or (m.completed_at is not None and self.t - m.completed_at < MISSION_COMPLETED_DISPLAY_STEPS)],
            "pedestrians": [{"pos": p["pos"].copy()} for p in self.pedestrians],
            "completed": self.total_completed
        })

    def _resolve_deadlock(self, agv, reserved):
        # Resolver atoron entre dos AGVs. Devuelve True si encontro un desvio
        # valido, False si no (para que quien llama sepa si debe seguir
        # escalando en vez de reiniciar el conteo y repetir el mismo intento
        # fallido para siempre).
        if not agv.path:
            return False

        # Si hay otro AGV muy cerca, normalmente solo maniobra el de mayor id
        # y el de menor id espera, para que no maniobren los dos a la vez y
        # queden moviendose de un lado a otro. Pero si ya llevamos varios
        # ciclos sin resolver nada (el de mayor id tambien esta atorado, p.ej.
        # contra un rack), esa prioridad estricta produce un livelock: nadie
        # se mueve nunca. Tras esperar suficiente, se permite que el de menor
        # id tambien intente su propio desvio.
        own_num = int(agv.agv_id.split("-")[1])
        nearby_higher = any(
            oid != agv.agv_id
            and np.linalg.norm(agv.pos - opos) < AGV_SAFETY_RADIUS * 2
            and int(oid.split("-")[1]) > own_num
            for oid, opos in reserved.items()
        )
        escalating = agv.stuck_steps >= DEADLOCK_THRESHOLD * 3
        if nearby_higher and not escalating:
            return False

        target = agv.path[0]
        direction = target - agv.pos
        dist = np.linalg.norm(direction)
        if dist < 1e-6:
            return False

        unit = direction / dist
        perp = np.array([-unit[1], unit[0]])

        # Mientras mas tiempo lleve atorado, se prueban mas angulos y mas
        # distancias de desvio, en vez de repetir para siempre los dos mismos
        # puntos perpendiculares (que pueden estar bloqueados permanentemente
        # por un rack de un lado y otro AGV del otro).
        angle_steps = min(1 + agv.stuck_steps // DEADLOCK_THRESHOLD, 4)
        candidate_dirs = [perp, -perp]
        for k in range(1, angle_steps):
            theta = k * (np.pi / (2 * (angle_steps + 1)))
            cos_t, sin_t = np.cos(theta), np.sin(theta)
            rot = np.array([[cos_t, -sin_t], [sin_t, cos_t]])
            candidate_dirs.append(rot @ perp)
            candidate_dirs.append(rot @ -perp)
            candidate_dirs.append(rot.T @ perp)
            candidate_dirs.append(rot.T @ -perp)

        base_detour = AGV_SAFETY_RADIUS + CELL_SIZE * 2
        distance_scales = [1.0, 1.5, 2.0] if agv.stuck_steps >= DEADLOCK_THRESHOLD * 2 else [1.0]

        for scale in distance_scales:
            detour_dist = base_detour * scale
            for side in candidate_dirs:
                candidate = agv.pos + side * detour_dist
                candidate = np.clip(candidate, [CELL_SIZE, CELL_SIZE], [WIDTH - CELL_SIZE, HEIGHT - CELL_SIZE])
                gx, gy = world_to_grid(candidate)
                if NAV_GRID[gy, gx] == 0:
                    clear = all(
                        np.linalg.norm(candidate - other_pos) >= AGV_SAFETY_RADIUS
                        for oid, other_pos in reserved.items() if oid != agv.agv_id
                    )
                    if clear:
                        # Conectar el desvío y el destino final por la cuadrícula.
                        # Insertar un punto aislado producía atajos a través del rack.
                        candidate = grid_to_world((gx, gy))
                        outbound = find_path_grid(agv.pos, candidate, NAV_GRID)
                        inbound = find_path_grid(candidate, agv.path[-1], NAV_GRID)
                        route = outbound + inbound
                        points = [agv.pos] + route
                        if not all(segment_clear_of_obstacles(a, b) for a, b in zip(points, points[1:])):
                            continue
                        agv.path = route
                        self.mission_manager.log.append(f"[MANIOBRA] {agv.agv_id} se desvía para evitar bloqueo")
                        return True
        return False

    def _move_with_collision_avoidance(self, agv, reserved):
        if not agv.path:
            agv.stuck_steps = 0
            return

        original_speed = agv.speed
        for fraction in (1.0, 0.5, 0.25):
            agv.speed = original_speed * fraction
            next_pos = agv.peek_next_position()
            blocked = not segment_clear_of_obstacles(agv.pos, next_pos)
            for other_id, other_pos in reserved.items():
                if other_id == agv.agv_id:
                    continue
                if np.linalg.norm(next_pos - other_pos) < AGV_SAFETY_RADIUS:
                    blocked = True
                    break
            if not blocked:
                for ped in self.pedestrians:
                    movement = next_pos - agv.pos
                    length_sq = float(np.dot(movement, movement))
                    alpha = 0.0 if length_sq < 1e-9 else float(np.clip(np.dot(ped["pos"] - agv.pos, movement) / length_sq, 0, 1))
                    if np.linalg.norm(agv.pos + movement * alpha - ped["pos"]) < PEDESTRIAN_RADIUS:
                        blocked = True
                        break
            if not blocked:
                agv.follow_path()
                agv.speed = original_speed
                agv.stuck_steps = 0
                reserved[agv.agv_id] = agv.pos.copy()
                return

        agv.speed = original_speed
        agv.stuck_steps += 1

        if agv.stuck_steps >= DEADLOCK_THRESHOLD:
            if self._resolve_deadlock(agv, reserved):
                agv.stuck_steps = 0
            agv.speed = original_speed

    def step(self):
        # 1. Generación de misiones
        self.run_flow_generator()

        # 1b. Eventos dinamicos (peatones, alarmas de estacion)
        self.update_pedestrians()
        self.update_station_alarms()

        # 2. Subasta de misiones pendientes: el Mission Manager solo publica
        # y reune las pujas (tablon de anuncios); cada AGV decide por si mismo
        # si gano, viendo el mismo tablon (`determine_if_winner`), y se
        # autoasigna la mision (`accept_mission`). El Mission Manager nunca
        # compara AGVs ni elige un ganador.
        for m in self.mission_manager.missions.values():
            if m.status == MISSION_PENDING:
                self.mission_manager.publish_mission(m)
                bids = self.mission_manager.collect_bids(m, self.agvs)
                if not bids:
                    continue
                for agv in self.agvs:
                    if agv.determine_if_winner(bids):
                        agv.accept_mission(m)
                        m.status = MISSION_ASSIGNED
                        m.assigned_to = agv.agv_id
                        m.started_at = self.t
                        self.pallets[m.pallet_id].state = P_RESERVED
                        self.mission_manager.log.append(f"{agv.agv_id} gana la Misión {m.id}")
                        break

        # 3. Comportamiento y Movimiento de los AGVs

        # Posiciones ocupadas al inicio del paso
        reserved = {a.agv_id: a.pos.copy() for a in self.agvs}

        # Prioridad, primero quien va a cargar, luego menor bateria primero
        move_order = sorted(self.agvs, key=lambda a: (a.state != AGV_CHARGING, a.battery))

        for agv in move_order:
            # --- M4: conteo de pasos por estado (para utilizacion de la flota) ---
            if agv.state in (AGV_MOVING_TO_PALLET, AGV_TRANSPORTING):
                agv.active_steps += 1
            elif agv.state == AGV_CHARGING:
                agv.charging_steps += 1
            elif agv.state == AGV_IDLE:
                agv.idle_steps += 1

            # Transición a recarga
            if agv.state == AGV_IDLE and agv.battery <= LOW_BATTERY_THRESHOLD:
              if agv.go_to_recharge(self.chargers):
                  self.mission_manager.log.append(f"[BATERÍA] {agv.agv_id} ({agv.battery:.1f}%) se dirige a recargar")
              else:
                  self.mission_manager.log.append(f"[BATERÍA] {agv.agv_id} ({agv.battery:.1f}%) espera cargador libre")

            # Proceso de carga en estación
            elif agv.state == AGV_CHARGING:
              self._move_with_collision_avoidance(agv, reserved)
              if len(agv.path) == 0:
                  agv.battery = min(100.0, agv.battery + 4.0)
                  if agv.battery >= CHARGED_BATTERY_THRESHOLD:
                      agv.state = AGV_IDLE
                      if agv.charger is not None:
                          agv.charger["occupied_by"] = None
                          agv.charger = None
                      self.mission_manager.log.append(f"[BATERÍA] {agv.agv_id} recargado ({agv.battery:.1f}%), vuelve a IDLE")

            # Movimiento hacia el pallet
            elif agv.state == AGV_MOVING_TO_PALLET:
                pallet = self.pallets[agv.current_mission.pallet_id]
                self._move_with_collision_avoidance(agv, reserved)

                if len(agv.path) == 0:
                    agv.state = AGV_TRANSPORTING
                    pallet.state = P_BEING_TRANSPORTED
                    pallet.storage_zone = None
                    agv.path = find_path_grid(agv.pos, agv.current_mission.destination, NAV_GRID)

                    if agv.current_mission.origin_station_id is not None:
                        self.stations_by_name[agv.current_mission.origin_station_id].release()
                    else:
                        self.production_line.release_by_pallet(pallet.id)

                    self.mission_manager.log.append(f"[EVENTO] {agv.agv_id} recogió {pallet.id}")

            # Transporte hacia la zona de entrega
            elif agv.state == AGV_TRANSPORTING:
                pallet = self.pallets[agv.current_mission.pallet_id]
                self._move_with_collision_avoidance(agv, reserved)
                pallet.pos = agv.pos.copy()

                if len(agv.path) == 0:
                    agv.state = AGV_IDLE
                    agv.current_mission.status = MISSION_COMPLETED
                    agv.current_mission.completed_at = self.t
                    pallet.state = P_DELIVERED
                    pallet.storage_zone = agv.current_mission.dest_station_id
                    agv.completed_missions_count += 1
                    self.total_completed += 1

                    # La estacion de destino ahora tiene el pallet fisicamente
                    if agv.current_mission.dest_station_id is not None:
                        self.stations_by_name[agv.current_mission.dest_station_id].occupy(pallet.id)

                    self.mission_manager.log.append(f"[EVENTO] {agv.agv_id} entregó {pallet.id} ({agv.current_mission.id} completada)")
                    agv.current_mission = None

        self._record_frame()

