class ProductionLine:

    def __init__(self, outlet_positions):
        self.outlets = [{"pos": np.array(p, dtype=float), "pallet_id": None} for p in outlet_positions]

    def free_outlets(self):
        return [o for o in self.outlets if o["pallet_id"] is None]

    def occupy_outlet(self, outlet, pallet_id):
        outlet["pallet_id"] = pallet_id

    def release_by_pallet(self, pallet_id):
        for o in self.outlets:
            if o["pallet_id"] == pallet_id:
                o["pallet_id"] = None

def find_path_grid(start_pos, goal_pos, grid):
    start = world_to_grid(start_pos)
    goal = world_to_grid(goal_pos)

    if start == goal:
        return [np.array(goal_pos, dtype=float)]

    queue = deque([start])
    came_from = {start: None}
    directions = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    found = False

    while queue:
        current = queue.popleft()
        if current == goal:
            found = True
            break

        for dx, dy in directions:
            neighbor = (current[0] + dx, current[1] + dy)
            nx, ny = neighbor

            if 0 <= nx < GRID_W and 0 <= ny < GRID_H:
                if (grid[ny, nx] == 0 or neighbor == goal) and neighbor not in came_from:
                    came_from[neighbor] = current
                    queue.append(neighbor)

    if not found:
        return [np.array(goal_pos, dtype=float)]

    path = []
    curr = goal
    while curr is not None:
        path.append(grid_to_world(curr))
        curr = came_from[curr]
    path.reverse()
    path[-1] = np.array(goal_pos, dtype=float)
    return path

