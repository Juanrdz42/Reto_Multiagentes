def segment_clear_of_obstacles(start, end, clearance=AGV_CLEARANCE):
    """Comprueba el segmento completo, no solo su celda de destino."""
    for pos in (start, end):
        if not (clearance <= pos[0] <= NAV_RIGHT - clearance
                and clearance <= pos[1] <= HEIGHT - clearance):
            return False
    for zone in zones_custom:
        enter, leave = 0.0, 1.0
        for axis, key, size in ((0, "x", "width"), (1, "y", "height")):
            low = zone[key] - clearance
            high = zone[key] + zone[size] + clearance
            delta = end[axis] - start[axis]
            if abs(delta) < 1e-9:
                if start[axis] <= low or start[axis] >= high:
                    break
            else:
                a, b = sorted(((low - start[axis]) / delta, (high - start[axis]) / delta))
                enter, leave = max(enter, a), min(leave, b)
                if enter >= leave:
                    break
        else:
            if enter < leave:
                return False
    return True

