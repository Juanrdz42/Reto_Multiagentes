def charger_route(position, charger):
    """Ruta mínima estática real, reutilizando un árbol BFS por cargador."""
    target = np.array(charger["pos"], dtype=float)
    goal = world_to_grid(target)
    if goal not in CHARGER_TREES:
        tree = {goal: None}
        queue = deque([goal])
        while queue:
            cell = queue.popleft()
            for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                neighbor = cell[0]+dx, cell[1]+dy
                x, y = neighbor
                if 0 <= x < GRID_W and 0 <= y < GRID_H and NAV_GRID[y,x] == 0 and neighbor not in tree:
                    tree[neighbor] = cell
                    queue.append(neighbor)
        CHARGER_TREES[goal] = tree
    tree = CHARGER_TREES[goal]
    cell = world_to_grid(position)
    if cell not in tree:
        return None
    route = []
    while cell is not None:
        route.append(grid_to_world(cell))
        cell = tree[cell]
    route.append(target)
    return route

def route_energy(position, route):
    if route is None:
        return float("inf")
    points = [position] + route
    return sum(float(np.linalg.norm(b-a)) for a,b in zip(points, points[1:])) * ENERGY_PER_UNIT


