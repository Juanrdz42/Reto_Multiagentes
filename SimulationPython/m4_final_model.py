def find_path_grid(start_pos, goal_pos, grid):
    start = world_to_grid(start_pos)
    goal = world_to_grid(goal_pos)

    if start == goal:
        return [np.array(goal_pos, dtype=float)]

    queue = deque([start])
    came_from = {start: None}
    directions = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    found = False

    while queue:
        current = queue.popleft()
        if current == goal:
            found = True
            break

        for dx, dy in directions:
            neighbor = (current[0] + dx, current[1] + dy)
            nx, ny = neighbor

            if 0 <= nx < GRID_W and 0 <= ny < GRID_H:
                if (grid[ny, nx] == 0 or neighbor == goal) and neighbor not in came_from:
                    came_from[neighbor] = current
                    queue.append(neighbor)

    if not found:
        return [np.array(goal_pos, dtype=float)]

    path = []
    curr = goal
    while curr is not None:
        path.append(grid_to_world(curr))
        curr = came_from[curr]
    path.reverse()
    path[-1] = np.array(goal_pos, dtype=float)
    return path


def find_path_astar_congestion(start_pos, goal_pos, grid, busy_cells,
                                radius=ASTAR_CONGESTION_RADIUS_CELLS,
                                cost=ASTAR_CONGESTION_COST):
    """A* con costo extra por celda cercana a un AGV en movimiento (busy_cells,
    en coordenadas de rejilla). Con busy_cells vacio, produce el mismo camino
    minimo que `find_path_grid` (BFS), solo que via A*."""
    start = world_to_grid(start_pos)
    goal = world_to_grid(goal_pos)
    if start == goal:
        return [np.array(goal_pos, dtype=float)]

    busy = busy_cells - {start}

    def extra_cost(cell):
        if not busy:
            return 0.0
        cx, cy = cell
        return sum(cost for bx, by in busy if abs(cx - bx) + abs(cy - by) <= radius)

    directions = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    open_heap = [(0.0, start)]
    g_score = {start: 0.0}
    came_from = {start: None}
    closed = set()

    while open_heap:
        _, current = heapq.heappop(open_heap)
        if current in closed:
            continue
        closed.add(current)
        if current == goal:
            break
        cx, cy = current
        for dx, dy in directions:
            neighbor = (cx + dx, cy + dy)
            nx, ny = neighbor
            if 0 <= nx < GRID_W and 0 <= ny < GRID_H:
                if grid[ny, nx] == 0 or neighbor == goal:
                    step_cost = 1.0 + extra_cost(neighbor)
                    tentative = g_score[current] + step_cost
                    if neighbor not in g_score or tentative < g_score[neighbor] - 1e-9:
                        g_score[neighbor] = tentative
                        came_from[neighbor] = current
                        h = abs(goal[0] - nx) + abs(goal[1] - ny)
                        heapq.heappush(open_heap, (tentative + h, neighbor))

    if goal not in came_from:
        return [np.array(goal_pos, dtype=float)]

    path = []
    curr = goal
    while curr is not None:
        path.append(grid_to_world(curr))
        curr = came_from[curr]
    path.reverse()
    path[-1] = np.array(goal_pos, dtype=float)
    return path


