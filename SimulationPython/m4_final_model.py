def plan_path(agv, target_pos):
    """Punto unico donde se decide como planear una ruta: BFS (M4 original)
    o A* con penalizacion por congestion (M4-EXT), segun `model.p.routing`.

    La congestion se lee de `model._routing_busy_cells`, una FOTO tomada una
    sola vez al inicio de cada `step()` (ver `DistributionCenter.step`), no
    las posiciones en vivo de `self.agvs`. Sin la foto, dos llamadas a
    `plan_path` dentro del mismo step (p.ej. un AGV que ya se movio este step
    vs uno que no) verian una mezcla inconsistente de posiciones "de este
    step" y "del step anterior", lo que en la practica generaba MAS
    conflictos de ruta en vez de menos."""
    routing_mode = getattr(agv.model.p, "routing", ROUTING_BFS)
    if routing_mode == ROUTING_ASTAR:
        busy_cells = getattr(agv.model, "_routing_busy_cells", set()) - {world_to_grid(agv.pos)}
        return find_path_astar_congestion(agv.pos, target_pos, NAV_GRID, busy_cells)
    return find_path_grid(agv.pos, target_pos, NAV_GRID)

