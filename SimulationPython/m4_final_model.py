    def _current_target(self, agv):
        """A donde se dirige el AGV en este momento, para poder re-planear
        la ruta completa desde cero (ver `_resolve_deadlock`)."""
        if agv.state == AGV_MOVING_TO_PALLET and agv.current_mission is not None:
            return agv.current_mission.origin
        if agv.state == AGV_TRANSPORTING and agv.current_mission is not None:
            return agv.current_mission.destination
        if agv.state == AGV_CHARGING and agv.charger is not None:
            return np.array(agv.charger["pos"], dtype=float)
        return None

    def _resolve_deadlock(self, agv, reserved):
        """Replanear alrededor de vehículos; si no hay paso, retroceder a una zona libre."""
        target = self._current_target(agv)
        if target is None:
            return False
        others = [pos for oid, pos in reserved.items() if oid != agv.agv_id]
        def clear(a, b):
            if not segment_clear_of_obstacles(a, b):
                return False
            delta = b - a
            length = float(np.dot(delta, delta))
            for pos in others:
                alpha = 0 if length < 1e-9 else float(np.clip(np.dot(pos-a, delta)/length, 0, 1))
                if np.linalg.norm(a + alpha*delta - pos) < AGV_SAFETY_RADIUS - 1e-6:
                    return False
            return True
        start = world_to_grid(agv.pos)
        goal = world_to_grid(target)
        queue = deque([start])
        parent = {start: None}
        found = None
        best = start
        best_score = -float("inf")
        while queue:
            cell = queue.popleft()
            point = agv.pos if cell == start else grid_to_world(cell)
            if cell == goal and clear(point, target):
                found = cell
                break
            distance = np.linalg.norm(point - agv.pos)
            if 20 <= distance <= 90:
                separation = min(np.linalg.norm(point - other) for other in others)
                score = min(separation, AGV_SAFETY_RADIUS * 2) - distance * 0.1
                if score > best_score:
                    best, best_score = cell, score
            for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                neighbor = (cell[0]+dx, cell[1]+dy)
                nx, ny = neighbor
                if not (0 <= nx < GRID_W and 0 <= ny < GRID_H) or neighbor in parent or NAV_GRID[ny,nx]:
                    continue
                if clear(point, grid_to_world(neighbor)):
                    parent[neighbor] = cell
                    queue.append(neighbor)
        destination = found if found is not None else best
        if destination == start:
            return False
        route = []
        cell = destination
        while cell != start:
            route.append(grid_to_world(cell))
            cell = parent[cell]
        route.reverse()
        if found is not None:
            route.append(np.array(target, dtype=float))
        else:
            # Conservar el destino de la misión; no confundir ceder el paso con entregar.
            route += find_path_grid(route[-1], target, NAV_GRID)[1:]
        if agv.state == AGV_CHARGING and route_energy(agv.pos, route) + 1.0 >= agv.battery:
            return False
        agv.path = route
        self.mission_manager.log.append(f"[MANIOBRA] {agv.agv_id} replantea con vehículos como obstáculos")
        return True

    def _move_with_collision_avoidance(self, agv, reserved):
        if not agv.path:
            agv.stuck_steps = 0
            return

        original_speed = agv.speed
        for fraction in (1.0, 0.5, 0.25):
            agv.speed = original_speed * fraction
            next_pos = agv.peek_next_position()
            blocked = not segment_clear_of_obstacles(agv.pos, next_pos)
            if agv.state == AGV_CHARGING and route_energy(agv.pos, agv.path) + 1.0 >= agv.battery:
                blocked = True
            for other_id, other_pos in reserved.items():
                if other_id == agv.agv_id:
                    continue
                if np.linalg.norm(next_pos - other_pos) < AGV_SAFETY_RADIUS:
                    blocked = True
                    break
            if not blocked:
                for ped in self.pedestrians:
                    if np.linalg.norm(next_pos - ped["pos"]) < PEDESTRIAN_RADIUS:
                        blocked = True
                        break
            if not blocked:
                agv.follow_path()
                agv.speed = original_speed
                agv.stuck_steps = 0
                agv.failed_resolve_streak = 0
                reserved[agv.agv_id] = agv.pos.copy()
                return

        agv.speed = original_speed
        agv.stuck_steps += 1

        if agv.stuck_steps >= DEADLOCK_THRESHOLD:
            resolved = self._resolve_deadlock(agv, reserved)
            agv.stuck_steps = 0
            agv.speed = original_speed
            # A diferencia de stuck_steps (que se resetea siempre), este contador
            # SOLO se resetea si el desvio funciono -- si no, sigue creciendo
            # aunque stuck_steps vuelva a 0, para que _resolve_deadlock sepa
            # cuantos intentos van fallando de verdad y pueda escalar en serio.
            agv.failed_resolve_streak = 0 if resolved else agv.failed_resolve_streak + 1

    def step(self):
        # Foto de posiciones de AGVs en movimiento, tomada UNA sola vez al
        # inicio del step (antes de que nadie se mueva este step). Todas las
        # llamadas a `plan_path` durante este step usan esta misma foto, para
        # que la nocion de "congestion" sea consistente en vez de una mezcla
        # de posiciones ya actualizadas y sin actualizar dentro del mismo step.
        self._routing_busy_cells = {
            world_to_grid(a.pos) for a in self.agvs if a.state in ROUTING_BUSY_STATES
        }

        # 1. Generación de misiones
        self.run_flow_generator()

        # 1b. Eventos dinamicos (peatones, alarmas de estacion)
        self.update_pedestrians()
        self.update_station_alarms()

        # Recargar tiene prioridad sobre aceptar o continuar una misión.
        for agv in self.agvs:
            if agv.needs_recharge():
                agv.go_to_recharge(self.chargers)

        # 2. Subasta de misiones pendientes: el Mission Manager solo publica
        # y reune las pujas (tablon de anuncios); cada AGV decide por si mismo
        # si gano, viendo el mismo tablon (`determine_if_winner`), y se
        # autoasigna la mision (`accept_mission`). El Mission Manager nunca
        # compara AGVs ni elige un ganador.
        for m in self.mission_manager.missions.values():
            if m.status == MISSION_PENDING:
                self.mission_manager.publish_mission(m)
                bids = self.mission_manager.collect_bids(m, self.agvs)
                if not bids:
                    continue
                for agv in self.agvs:
                    if agv.determine_if_winner(bids):
                        agv.accept_mission(m)
                        m.status = MISSION_ASSIGNED
                        m.assigned_to = agv.agv_id
                        m.started_at = self.t
                        self.pallets[m.pallet_id].state = P_RESERVED
                        self.mission_manager.log.append(f"{agv.agv_id} gana la Misión {m.id}")
                        break

        # 3. Comportamiento y Movimiento de los AGVs

        # Posiciones ocupadas al inicio del paso
        reserved = {a.agv_id: a.pos.copy() for a in self.agvs}

        # Prioridad, primero quien va a cargar, luego menor bateria primero
        move_order = sorted(self.agvs, key=lambda a: (a.state != AGV_CHARGING, a.battery))

        for agv in move_order:
            # --- M4: conteo de pasos por estado (para utilizacion de la flota) ---
            if agv.state in (AGV_MOVING_TO_PALLET, AGV_TRANSPORTING):
                agv.active_steps += 1
            elif agv.state == AGV_CHARGING:
                agv.charging_steps += 1
            elif agv.state == AGV_IDLE:
                agv.idle_steps += 1

            # Viajar, esperar turno y cargar son fases distintas.
            if agv.state == AGV_CHARGING:
                if agv.charger is None:
                    agv.go_to_recharge(self.chargers)
                if agv.charger is not None:
                    self._move_with_collision_avoidance(agv, reserved)
                    at_charger = np.linalg.norm(agv.pos - np.array(agv.charger["pos"])) < 0.001
                    agv.charge_phase = "CHARGING" if at_charger else "TO_CHARGER"
                    if at_charger:
                        agv.battery = min(100.0, agv.battery + 4.0)
                        if agv.battery >= CHARGED_BATTERY_THRESHOLD:
                            agv.charger["occupied_by"] = None
                            agv.charger = None
                            agv.state = agv.suspended_state if agv.current_mission is not None else AGV_IDLE
                            agv.charge_phase = ""
                            target = self._current_target(agv)
                            agv.path = plan_path(agv, target) if target is not None else []
                if agv.current_mission is not None:
                    pallet = self.pallets[agv.current_mission.pallet_id]
                    if pallet.state == P_BEING_TRANSPORTED:
                        pallet.pos = agv.pos.copy()

            # Movimiento hacia el pallet
            elif agv.state == AGV_MOVING_TO_PALLET:
                pallet = self.pallets[agv.current_mission.pallet_id]
                self._move_with_collision_avoidance(agv, reserved)

                if len(agv.path) == 0:
                    agv.state = AGV_TRANSPORTING
                    pallet.state = P_BEING_TRANSPORTED
                    agv.path = plan_path(agv, agv.current_mission.destination)

                    if agv.current_mission.origin_station_id is not None:
                        self.stations_by_name[agv.current_mission.origin_station_id].release()
                    else:
                        self.production_line.release_by_pallet(pallet.id)

                    self.mission_manager.log.append(f"[EVENTO] {agv.agv_id} recogió {pallet.id}")

            # Transporte hacia la zona de entrega
            elif agv.state == AGV_TRANSPORTING:
                pallet = self.pallets[agv.current_mission.pallet_id]
                self._move_with_collision_avoidance(agv, reserved)
                pallet.pos = agv.pos.copy()

                if len(agv.path) == 0:
                    agv.state = AGV_IDLE
                    agv.current_mission.status = MISSION_COMPLETED
                    agv.current_mission.completed_at = self.t
                    pallet.state = P_DELIVERED
                    agv.completed_missions_count += 1
                    self.total_completed += 1

                    # La estacion de destino ahora tiene el pallet fisicamente
                    if agv.current_mission.dest_station_id is not None:
                        self.stations_by_name[agv.current_mission.dest_station_id].occupy(pallet.id)

                    self.mission_manager.log.append(f"[EVENTO] {agv.agv_id} entregó {pallet.id} ({agv.current_mission.id} completada)")
                    agv.current_mission = None

        for agv in self.agvs:
            if agv.state != AGV_CHARGING and agv.battery <= LOW_BATTERY_THRESHOLD:
                agv.go_to_recharge(self.chargers)
        self._record_frame()

