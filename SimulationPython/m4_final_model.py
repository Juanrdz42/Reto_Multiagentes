def edge_point(zone, side, margin=SERVICE_MARGIN):
    x, y, w, h = zone["x"], zone["y"], zone["width"], zone["height"]
    if side == "west":
        return (x - margin, y + h / 2)
    if side == "east":
        return (x + w + margin, y + h / 2)
    if side == "south":
        return (x + w / 2, y - margin)
    if side == "north":
        return (x + w / 2, y + h + margin)
    raise ValueError(side)

