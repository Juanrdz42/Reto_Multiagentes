def build_occupancy_grid(zones):
    # Centros transitables: el cuerpo completo debe caber fuera de zonas y paredes.
    xs = (np.arange(GRID_W) + 0.5) * CELL_SIZE
    ys = (np.arange(GRID_H) + 0.5) * CELL_SIZE
    xx, yy = np.meshgrid(xs, ys)
    blocked = ((xx < AGV_CLEARANCE) | (xx > NAV_RIGHT - AGV_CLEARANCE)
               | (yy < AGV_CLEARANCE) | (yy > HEIGHT - AGV_CLEARANCE))
    for z in zones:
        blocked |= ((xx > z["x"] - AGV_CLEARANCE)
                    & (xx < z["x"] + z["width"] + AGV_CLEARANCE)
                    & (yy > z["y"] - AGV_CLEARANCE)
                    & (yy < z["y"] + z["height"] + AGV_CLEARANCE))
    return blocked.astype(int)

